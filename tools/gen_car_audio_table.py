#!/usr/bin/env python3
"""Generates src/game/indep/Sound/CarAudioTable.h (ISSUES.md #128).
Usage: mips_init_run.py SLES_527.25 1adad0 caraudio.json; gen_car_audio_table.py SLES_527.25 caraudio.json OUT.h"""
import json, struct, sys

elf = open(sys.argv[1], 'rb').read()
ph = struct.unpack_from('<I', elf, 0x1c)[0]
_, off, v, _, fs, ms = struct.unpack_from('<IIIIII', elf, ph)
img = bytearray(elf[off:off + fs]) + bytearray(ms - fs)
for s, e, h in json.load(open(sys.argv[2]))['runs']:
    if v <= s and e <= v + ms:
        img[s - v:e - v] = bytes.fromhex(h)
def u32(a): return struct.unpack_from('<I', img, a - v)[0]
def cstr(a):
    k = a - v
    return img[k:img.index(0, k)].decode()

# 0x00179e98 is a switch (not table data); its cases, read from the pseudocode.
SWITCH = {0: 0x16, 1: 10, 2: 6, 3: 0, 4: 0x13, 5: 5, 6: 0x17, 7: 7, 8: 0xe, 9: 0x15, 10: 9, 11: 0x1f, 12: 0x1c,
          13: 4, 14: 0x11, 15: 0x1e, 16: 0xc, 17: 3, 18: 0x18, 19: 8, 20: 0x20, 21: 0x1a, 22: 2, 23: 0xb,
          24: 1, 25: 0xd, 26: 0x14, 27: 0x1d, 29: 0x19, 30: 0xf}
rows = [struct.unpack_from('<12i', img, 0x4aca90 + r * 0x30 - v) for r in range(33)]
engines = [cstr(u32(0x4ab640 + i * 0x4c + 4)) for i in range(43)]
gears = [cstr(u32(0x4ad0c0 + i * 0x60)) for i in range(18)]
turbos = [cstr(u32(0x4adb98 + i * 0x18)) for i in range(15)]

def names(var, comment, items):
    out = [comment, 'static const char *const %s[%d] = {' % (var, len(items))]
    for i in range(0, len(items), 3):
        out.append('    ' + ' '.join('"%s",' % x for x in items[i:i + 3]))
    return out + ['};', '']

L = ['#pragma once',
     '// Generated by tools/gen_car_audio_table.py from SLES_527.25\'s audio static initializer 0x001adad0',
     '// (replayed by tools/mips_init_run.py, ISSUES.md #128) -- do not edit by hand.', '',
     'namespace CarAudio {', '',
     '// 0x00179e98: car type (GLOBALB 0x34600 record index) -> audio row; anything else -> 0x12.',
     'inline int RowForCarType(int type)', '{',
     '    static const signed char kRows[31] = {' + ', '.join(str(SWITCH.get(t, 0x12)) for t in range(31)) + '};',
     '    return type >= 0 && type < 31 ? kRows[type] : 0x12;', '}', '',
     '// 0x004aca90: per row, 4 engine upgrade levels x {engine, gearbox, turbo}. The level is picked by',
     '// 0x0017a118 from the installed engine parts (0x0f -> 1, 0x13 -> 2, 0x18 -> 3).',
     'struct Level {', '    signed char engine, gearbox, turbo;', '};',
     'static const Level kRowLevels[33][4] = {']
for r in rows:
    L.append('    {' + ', '.join('{%d, %d, %d}' % (r[k * 3], r[k * 3 + 1], r[k * 3 + 2]) for k in range(4)) + '},')
L += ['};', '']
L += names('kEngineBanks', '// 0x004ab640 (0x4c-byte records, +4): engine SPU bank in SOUND\\ENGINE\\.', engines)
L += names('kGearBanks', '// 0x004ad0c0 (0x60-byte records): gear-change bank in SOUND\\SHIFTING\\.', gears)
L += names('kTurboBanks', '// 0x004adb98 (0x18-byte records): turbo bank in SOUND\\TURBO\\.', turbos)
L += ['} // namespace CarAudio', '']
open(sys.argv[3], 'w').write('\n'.join(L))
